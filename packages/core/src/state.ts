/**
 * AgentState — the complete, serializable state of an agent conversation.
 * Pure data, no methods, no I/O. Serializable for checkpoint/resume.
 */

/** Status of the agent state machine */
export type AgentStatus =
  | "idle"                  // Waiting for user input
  | "calling_model"         // Model request in flight
  | "executing_tools"       // Tools dispatched, executing
  | "waiting_for_approval"  // Waiting for HITL approval
  | "waiting_for_input"     // Waiting for external input (e.g., sub-agent)
  | "cancelling"            // Cancel requested, cleaning up
  | "done";                 // Turn complete

/** A text content block */
export interface TextContent {
  type: "text";
  text: string;
}

/**
 * An image in the conversation. The bytes live in an AttachmentStore; state
 * carries only the reference, so a snapshot stays small enough to rewrite on
 * every checkpoint. The Runner resolves `id` to bytes when it assembles a
 * ModelRequest — the core never touches the image itself.
 */
export interface ImageContent {
  type: "image";
  source: {
    type: "ref";
    /** AttachmentStore key. */
    id: string;
    mediaType: string;
  };
  /** Pixel dimensions, recorded at ingest. Used for token estimation. */
  width?: number;
  height?: number;
}

/**
 * A structured, JSON-safe tool result projection. `kind` is a namespace
 * string (e.g. "lsp.locations") whose owner defines `data`'s shape. `text`
 * is the REQUIRED human/model-readable projection: every degradation path
 * (provider serialization, trimming, pruning) uses it, so consumers never
 * need to stringify `data` themselves. `data` MUST be JSON-safe — it
 * round-trips through state, transcript, and checkpoints.
 */
export interface StructuredContent {
  type: "structured";
  /** Namespace string, e.g. "lsp.locations". Owner defines data's shape. */
  kind: string;
  /** Arbitrary JSON-safe payload. Shape defined by `kind`'s owner. */
  data: unknown;
  /** REQUIRED text projection — the single degradation/cut exit. */
  text: string;
}

/** A tool use block in an assistant message */
export interface ToolUseContent {
  type: "tool_use";
  id: string;
  name: string;
  input: Record<string, unknown>;
}

/**
 * Blocks a tool may return to the model. Deliberately narrower than
 * ContentBlock: a tool result carries text and images, never nested
 * tool_use / tool_result / reasoning blocks.
 */
export type ToolResultBlock = TextContent | ImageContent | StructuredContent;

export interface ToolResultContent {
  type: "tool_result";
  toolUseId: string;
  /**
   * Always a block array in state. The reducer normalizes a tool's
   * plain-string result on the way in, so every consumer downstream
   * handles exactly one shape.
   */
  content: ToolResultBlock[];
  isError?: boolean;
}

/** Normalize a tool's author-facing result content into the state shape. */
export function normalizeToolResultContent(
  content: string | ToolResultBlock[],
): ToolResultBlock[] {
  return typeof content === "string" ? [{ type: "text", text: content }] : content;
}

/**
 * A reasoning block in an assistant message. Present so the model's own
 * thinking travels back into the next request: providers that require their
 * thinking blocks returned unmodified reject a tool loop that drops them.
 */
export interface ReasoningContent {
  type: "reasoning";
  text: string;
}

export type ContentBlock =
  | TextContent
  | ImageContent
  | StructuredContent
  | ToolUseContent
  | ToolResultContent
  | ReasoningContent;

/**
 * Stable identifier for a message. Stamped by the reducer from the optional
 * `Id` port on StepContext; hosts that construct messages themselves must
 * supply one. Used by pinning (`pinnedMessageIds`) and compaction to address
 * messages by id instead of by index.
 */
export interface SystemMessage {
  id: string;
  role: "system";
  content: string;
}

/** User message — from the human */
export interface UserMessage {
  id: string;
  role: "user";
  content: string | ContentBlock[];
}

/** Assistant message — from the model */
export interface AssistantMessage {
  id: string;
  role: "assistant";
  content: ContentBlock[];
  stopReason?: "end_turn" | "tool_use" | "max_tokens";
  /**
   * The route that produced this message. Adapters compare it against the
   * current route before trusting `modelMeta`: a message generated by another
   * model carries signatures the current one will reject.
   */
  source?: { providerId?: string; modelId: string };
  /**
   * Adapter-private replay state (provider signatures and the like), handed
   * over by the model event stream. The core stores and returns it verbatim
   * and never reads it.
   */
  modelMeta?: unknown;
}

/** Tool result message — output from tool execution */
export interface ToolResultMessage {
  id: string;
  role: "tool";
  content: ToolResultContent[];
}

export type Message =
  | SystemMessage
  | UserMessage
  | AssistantMessage
  | ToolResultMessage;

/** A tool call extracted from a model response, pending execution */
export interface PendingToolCall {
  id: string;
  name: string;
  input: Record<string, unknown>;
}

/** Read file record for edit_file gating (pure, serializable — survives resume) */
export interface ReadFileRecord {
  path: string;
  /** Incremented each time the path is (re)read or successfully written */
  version: number;
  /** File mtime (epoch ms) observed at read/write time; used for staleness comparison */
  mtime: number;
}

/** Lifecycle state of one todo entry. */
export type TodoStatus = "pending" | "in_progress" | "completed";

/**
 * One standing-plan entry. Deliberately minimal: no id (whole-list replace),
 * no priority, no activeForm.
 */
export interface TodoItem {
  content: string;
  status: TodoStatus;
}

/**
 * A detached sub-agent task tracked in serializable state. Deliberately
 * metadata-only: the promise handle stays with the Runner — a promise cannot
 * be serialized, and state only needs to record that a task exists so a
 * resumed Runner can discover it and fail it rather than wait forever.
 */
export interface BackgroundTask {
  id: string;
  subagentType?: string;
  /**
   * "running" can survive into a checkpoint. A resumed Runner holds no
   * handle for it and must fail it rather than wait forever.
   */
  status: "running" | "collected";
  startedAt: number;
}

/** The complete agent state */
export interface AgentState {
  messages: Message[];
  pendingTools: PendingToolCall[];
  status: AgentStatus;
  tokenBudget: number | undefined;
  /** Cumulative tokens consumed this turn (input + output), enforced against tokenBudget */
  tokensUsed: number;
  maxIterations: number;
  iterationCount: number;
  readFiles: ReadFileRecord[];
  /** Tool call pending HITL approval (serialized for checkpoint/resume) */
  pendingApprovalTool?: PendingToolCall;
  /**
   * Steering queue — user messages received mid-turn (during calling_model or
   * executing_tools). Injected into messages at the next turn boundary
   * (all tools complete → calling_model). Serializable for checkpoint/resume.
   */
  queuedUserInputs: UserMessage[];
  /** Cumulative tool calls dispatched this turn. Enforced against maxToolCalls. */
  toolCallCount: number;
  /**
   * Max tool calls allowed per turn. When exceeded, the reducer terminates
   * the turn with a "budget_exceeded" done state. Undefined = no limit.
   */
  maxToolCalls: number | undefined;
  /**
   * Maximum total cost ($) allowed per turn. When exceeded by the Runner,
   * a budget_exceeded input is fed to terminate the turn. Undefined = no limit.
   * Requires pricing configuration to be meaningful.
   */
  maxCostDollars: number | undefined;
  /**
   * Maximum raw token count allowed per turn (input + output).
   * Independent of pricing — always compares against raw token sums.
   * Undefined = no limit.
   */
  maxTokensPerTurn: number | undefined;
  /**
   * Maximum wall-clock milliseconds allowed per turn. When exceeded by the
   * Runner, a budget_exceeded input is fed to terminate the turn. Undefined = no limit.
   */
  maxWallclockMs: number | undefined;
  /**
   * Max consecutive identical failed tool calls before intervention (loop detection).
   * When the model repeats the same tool call with the same input K times and
   * all return errors, the turn is terminated. Undefined = no limit.
   */
  maxLoopCount: number | undefined;
  /**
   * Message ids that are "pinned" — never compressed by Compactor,
   * and stably positioned in ContextAssembler prefix slots.
   * Entries address `Message.id` (stable identity), not array indices.
   * Serializable for checkpoint/resume.
   */
  pinnedMessageIds?: string[];
  /**
   * Self-correction attempt counter (reset each turn).
   * Tracked in serializable state for checkpoint/resume.
   * When maxSelfCorrections is reached, forced termination occurs.
   */
  selfCorrectionCount: number;
  /** Max self-corrections per turn. Undefined = no limit (0 effectively disables self-correction). */
  maxSelfCorrections: number | undefined;
  /**
   * Standing todo list for this agent session.
   * - `undefined`: never written
   * - `[]`: explicitly cleared
   * - non-empty: current plan
   * Survives turns and checkpoint/resume. Never written by Compactor.
   */
  todos?: TodoItem[];
  /**
   * Background sub-agent tasks dispatched this turn.
   * - `undefined`: never written
   * - `[]`: explicitly cleared
   * - non-empty: tasks dispatched, each `running` until collected
   * Survives turns and checkpoint/resume; cleared by resetTurnForNextInput.
   */
  backgroundTasks?: BackgroundTask[];
  /**
   * Fingerprint of the workflow-mode reminder last announced to the model
   * (opaque host key; undefined = base / no workflow mode). Deliberately in
   * AgentState — not the ReducerState extension — so hosts seed it through
   * createInitialState() when rebuilding across a mode switch: without the
   * seed, the exit key `undefined` collides with a fresh flag and the exit
   * note never fires (spec 2026-09-25 §3.1-0).
   */
  _announcedWorkflowMode?: string;
}
